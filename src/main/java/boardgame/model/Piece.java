package boardgame.model;

/**
 * Represents the different piece types possible on the board.
 */
public enum Piece {

    /**
     * Represents an empty space, without a piece.
     */
    NONE,

    /**
     * Represents a red piece.
     */
    RED,

    /**
     * Represents a yellow piece.
     */
    YELLOW,

    /**
     * Represents a green piece.
     */
    GREEN
}
